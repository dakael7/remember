create table if not exists public.reminders (
  id bigint generated by default as identity primary key,
  chat_id bigint not null,
  task text not null,
  remind_at bigint not null,
  status text not null default 'pending'
    check (status in ('pending', 'sent', 'completed')),
  created_at timestamptz not null default now()
);

create index if not exists reminders_pending_remind_at_idx
  on public.reminders (remind_at)
  where status = 'pending';

alter table public.reminders enable row level security;

create table if not exists public.conversation_messages (
  id bigint generated by default as identity primary key,
  chat_id bigint not null,
  role text not null check (role in ('user', 'assistant')),
  content text not null,
  created_at timestamptz not null default now()
);

create index if not exists conversation_messages_chat_id_id_idx
  on public.conversation_messages (chat_id, id desc);

alter table public.conversation_messages enable row level security;
