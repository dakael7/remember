create table if not exists public.reminders (
  id bigint generated by default as identity primary key,
  chat_id bigint not null,
  task text not null,
  remind_at bigint not null,
  status text not null default 'pending'
    check (status in ('pending', 'sent', 'completed')),
  created_at timestamptz not null default now()
);

create index if not exists reminders_pending_remind_at_idx
  on public.reminders (remind_at)
  where status = 'pending';

alter table public.reminders enable row level security;

create table if not exists public.conversation_messages (
  id bigint generated by default as identity primary key,
  chat_id bigint not null,
  role text not null check (role in ('user', 'assistant')),
  content text not null,
  created_at timestamptz not null default now()
);

create index if not exists conversation_messages_chat_id_id_idx
  on public.conversation_messages (chat_id, id desc);

alter table public.conversation_messages enable row level security;

create table if not exists public.documents (
  id bigint generated by default as identity primary key,
  chat_id bigint not null,
  storage_path text not null unique,
  original_name text not null,
  mime_type text not null,
  size_bytes bigint not null check (size_bytes > 0),
  title text not null,
  document_type text,
  counterparty text,
  amount numeric(14, 2),
  currency text,
  due_date date,
  notes text,
  status text not null default 'draft'
    check (status in ('draft', 'active', 'archived')),
  due_notified_at timestamptz,
  created_at timestamptz not null default now()
);

alter table public.documents
  add column if not exists amount numeric(14, 2),
  add column if not exists currency text;

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'documents_amount_currency_valid'
      and conrelid = 'public.documents'::regclass
  ) then
    alter table public.documents
      add constraint documents_amount_currency_valid
      check (
        (amount is null or amount > 0)
        and (currency is null or currency ~ '^[A-Z]{3}$')
      );
  end if;
end;
$$;

create index if not exists documents_chat_id_created_at_idx
  on public.documents (chat_id, created_at desc);

create index if not exists documents_active_due_date_idx
  on public.documents (due_date)
  where status = 'active' and due_date is not null;

alter table public.documents enable row level security;

create table if not exists public.financial_records (
  id bigint generated by default as identity primary key,
  chat_id bigint not null,
  kind text not null check (kind in ('receivable', 'payable', 'debt')),
  description text not null,
  counterparty text,
  amount numeric(14, 2) not null check (amount > 0),
  currency text not null check (currency ~ '^[A-Z]{3}$'),
  paid_amount numeric(14, 2) not null default 0
    check (paid_amount >= 0 and paid_amount <= amount),
  due_date date,
  status text not null default 'draft'
    check (status in ('draft', 'pending', 'partially_paid', 'paid', 'cancelled')),
  document_id bigint references public.documents (id) on delete set null,
  due_notified_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists financial_records_chat_id_status_due_date_idx
  on public.financial_records (chat_id, status, due_date);

alter table public.financial_records enable row level security;

